"""Profile every dataset under data/raw and write docs/notes/dataset_profiles.md.

    python -m scripts.profile_datasets

For each CSV/JSON/JSONL file it reports: shape, columns (dtype, nulls, unique values),
detected date columns with their range, detected ticker/symbol columns with their overlap
with config/tickers.yaml, and a few truncated sample rows.
Open the generated markdown, read it, and paste it back when you want help writing adapters.
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from src.common.config import PROJECT_ROOT, get_settings, get_tickers, resolve_path
from src.common.logging_utils import get_logger

log = get_logger("profile_datasets")

DATE_HINT = re.compile(r"date|time|created|publish|timestamp", re.I)
TICKER_HINT = re.compile(r"ticker|symbol|stock", re.I)
SUFFIXES = {".csv", ".tsv", ".json", ".jsonl"}
SAMPLE_ROWS = 3
CELL_MAX = 110


LABEL_WORDS = {"positive", "negative", "neutral"}


def read_table(path: Path, header: int | None = 0) -> pd.DataFrame:
    """Read a tabular file, trying a few encodings for CSVs."""
    if path.suffix == ".jsonl":
        return pd.read_json(path, lines=True)
    if path.suffix == ".json":
        try:
            return pd.read_json(path)
        except ValueError:
            return pd.read_json(path, lines=True)
    sep = "\t" if path.suffix == ".tsv" else ","
    for enc in ("utf-8", "utf-8-sig", "latin-1"):
        try:
            return pd.read_csv(path, sep=sep, encoding=enc, low_memory=False, header=header)
        except UnicodeDecodeError:
            continue
    raise ValueError(f"Could not decode {path}")


def _clip(value: object) -> str:
    text = str(value).replace("\n", " ").replace("|", "/")
    return text if len(text) <= CELL_MAX else text[: CELL_MAX - 1] + "…"


def date_ranges(df: pd.DataFrame) -> list[str]:
    lines = []
    for col in df.columns:
        if not DATE_HINT.search(str(col)):
            continue
        parsed = pd.to_datetime(df[col], errors="coerce", utc=True)
        if parsed.notna().mean() >= 0.5:
            lines.append(f"- `{col}`: {parsed.min()} -> {parsed.max()} "
                         f"({parsed.notna().sum():,} parsable)")
    return lines


def ticker_overlap(df: pd.DataFrame, universe: set[str]) -> list[str]:
    lines = []
    for col in df.columns:
        if not TICKER_HINT.search(str(col)):
            continue
        values = df[col].dropna().astype(str).str.upper().str.strip()
        if values.nunique() > 2000:  # not a ticker-like column
            continue
        uniq = set(values.unique())
        hit = sorted(uniq & universe)
        rows = int(values.isin(universe).sum())
        lines.append(f"- `{col}`: {len(uniq)} distinct values; overlap with tickers.yaml = "
                     f"{len(hit)}/{len(universe)} {hit} ({rows:,} rows)")
        lines.append(f"  - most frequent: {values.value_counts().head(12).to_dict()}")
    return lines


def looks_headerless(df: pd.DataFrame) -> bool:
    """A sentiment label word used as a column name means row 1 was data, not a header."""
    return any(str(c).strip().lower() in LABEL_WORDS for c in df.columns)


def profile_file(path: Path, root: Path, universe: set[str]) -> str:
    df = read_table(path)
    note = ""
    if path.suffix in {".csv", ".tsv"} and looks_headerless(df):
        df = read_table(path, header=None)
        note = "NOTE: file has no header row; columns are numbered 0, 1, ..."
    out = [f"### `{path.relative_to(root)}`",
           f"{len(df):,} rows x {df.shape[1]} columns, {path.stat().st_size / 1e6:.1f} MB"]
    if note:
        out.append(note)
    out.append("")
    out += ["| column | dtype | nulls | unique | example |", "|---|---|---|---|---|"]
    for col in df.columns:
        s = df[col]
        example = _clip(s.dropna().iloc[0]) if s.notna().any() else ""
        out.append(f"| {_clip(col)} | {s.dtype} | {int(s.isna().sum()):,} | "
                   f"{s.nunique(dropna=True):,} | {example} |")

    dr = date_ranges(df)
    if dr:
        out += ["", "**Date columns**", *dr]
    tk = ticker_overlap(df, universe)
    if tk:
        out += ["", "**Ticker-like columns**", *tk]

    low_card = [c for c in df.columns
                if df[c].dtype == object and 1 < df[c].nunique() <= 12]
    for col in low_card[:3]:
        out += ["", f"**Value counts for `{col}`**: {df[col].value_counts().to_dict()}"]

    out += ["", f"**First {SAMPLE_ROWS} rows**", "", "```"]
    out += [_clip(row) for row in df.head(SAMPLE_ROWS).to_dict("records")]
    out += ["```", ""]
    return "\n".join(out)


def main() -> None:
    raw_root = resolve_path(get_settings().paths.data_raw)
    universe = set(get_tickers())
    sections = ["# Dataset profiles", "",
                "Generated by `python -m scripts.profile_datasets`. Do not edit by hand.", ""]

    files = sorted(
        p for p in raw_root.rglob("*")
        if p.is_file()
        and p.suffix.lower() in SUFFIXES
        and "gdelt" not in p.relative_to(raw_root).parts
    )
    if not files:
        log.error("No CSV/JSON files found under %s. Run scripts.download_data first.", raw_root)
        return
    for path in files:
        if "prices" in path.parts:  # price files are handled by fetch_prices
            continue
        log.info("profiling %s", path.relative_to(PROJECT_ROOT))
        try:
            sections.append(profile_file(path, raw_root, universe))
        except Exception as exc:  # noqa: BLE001
            sections.append(f"### `{path.relative_to(raw_root)}`\nCould not profile: {exc}\n")
            log.error("failed on %s: %s", path, exc)

    out_path = PROJECT_ROOT / "docs" / "notes" / "dataset_profiles.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(sections), encoding="utf-8")
    log.info("wrote %s", out_path)


if __name__ == "__main__":
    main()
